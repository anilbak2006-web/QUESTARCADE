// ======================================================
// Create a consistent question object for every quiz definition.
// ======================================================

const question = (
    quesitonText,
    options,
    correctAnswer = null,
    scores = null,
    optionDetails = null
) => ({
    quesiton: quesitonText,
    options,
    correctAnswer,
    scores,
    optionDetails,
});


// ======================================================
// Build option descriptions and character mappings for personality quizzes.
// ======================================================

function personalityQuestion(quesitonText, options, scores) {
    const optionDetails = {};

    Object.entries(scores).forEach(([letter, characters]) => {
        const validCharacters = characters.filter(
            (character) => characterDetails[character]
        );

        const descriptions = validCharacters.map(
            (character) => characterDetails[character].description
        );

        const image =
            validCharacters.length > 0
                ? characterDetails[validCharacters[0]].image
                : "";

        let description = "";

        if (descriptions.length === 1) {
            description = descriptions[0];
        } else if (descriptions.length === 2) {
            description = `${descriptions[0]} Ayrıca ${descriptions[1].charAt(0).toLowerCase()}${descriptions[1].slice(1)}`;
        } else if (descriptions.length > 2) {
            description = `${descriptions[0]} Bu seçeneğin diğer tarafında ise ${validCharacters
                .slice(1)
                .join(", ")} gibi daha çok farklı karakterlerin ortak özellikleri bulunuyor.`;
        } else {
            description = "Bu seçenek senin kişilik tercihlerini temsil ediyor.";
        }

        optionDetails[letter] = {
            description,
            image,
        };
    });

    return question(
        quesitonText,
        options,
        null,
        scores,
        optionDetails
    );
}


const asQuestImage = (value) => {
    if (!value) return "/LOGO.png";
    if (value.startsWith("http://") || value.startsWith("https://")) return value;
    if (value.startsWith("/")) return value;
    if (value.startsWith("QUEST_IMAGES/")) return `/${value}`;
    return `/QUEST_IMAGES/${value.replace(/\.png$/i, ".webp")}`;
};

